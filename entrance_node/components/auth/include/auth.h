/**
 * @file auth.h
 * @brief Console authentication, role checks, lockout and idle sessions.
 *
 * Security model (spec 14.2):
 *   - passwords are never stored, only PBKDF2-HMAC-SHA256 hashes;
 *   - each credential has its own 16-byte salt;
 *   - three failed attempts lock the account for 60 s;
 *   - a session ends after 300 s without activity;
 *   - the first-boot ADMIN must change its password before doing anything else.
 *
 * The PBKDF2 implementation is injected as a callback so this file stays pure
 * C and can be tested on the host with a fast deterministic stub. The target
 * implementation lives in auth_crypto.c (mbedtls).
 *
 * @author Opiyo Oscar
 * @requirements FR-AUTH-01..05, FR-CLI-02, INN-08
 */

#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#include "cocis_types.h"

#define COCIS_AUTH_SALT_LEN      16
#define COCIS_AUTH_HASH_LEN      32
#define COCIS_AUTH_NAME_LEN      24
#define COCIS_AUTH_MAX_USERS     4
#define COCIS_AUTH_ITERATIONS    1000   /* minimum allowed by the specification */

/* PBKDF2 callback: derive `out_len` bytes from password + salt. */
typedef bool (*cocis_pbkdf2_fn)(const char *password,
                                const uint8_t *salt, size_t salt_len,
                                uint32_t iterations,
                                uint8_t *out, size_t out_len);

typedef enum {
    COCIS_AUTH_OK = 0,
    COCIS_AUTH_BAD_CREDENTIALS,
    COCIS_AUTH_LOCKED,
    COCIS_AUTH_MUST_CHANGE,
    COCIS_AUTH_NOT_LOGGED_IN,
    COCIS_AUTH_FORBIDDEN,
} cocis_auth_result_t;

typedef struct {
    char username[COCIS_AUTH_NAME_LEN];
    uint8_t salt[COCIS_AUTH_SALT_LEN];
    uint8_t hash[COCIS_AUTH_HASH_LEN];
    cocis_role_t role;
    bool must_change;
    uint8_t fails;
    uint32_t locked_until_ms;
} cocis_credential_t;

typedef struct {
    cocis_credential_t users[COCIS_AUTH_MAX_USERS];
    size_t count;
    int session_user;          /* index, or -1 when logged out */
    uint32_t last_activity_ms;
} cocis_auth_t;

/** Reset the auth state; no users, no session. */
void cocis_auth_init(cocis_auth_t *auth);

/**
 * Add a credential with a pre-computed salt and hash (used when loading NVS
 * or when provisioning the first-boot admin).
 */
bool cocis_auth_add(cocis_auth_t *auth, const char *username, cocis_role_t role,
                    const uint8_t salt[COCIS_AUTH_SALT_LEN],
                    const uint8_t hash[COCIS_AUTH_HASH_LEN],
                    bool must_change);

/** Look up a credential by username, or NULL. */
const cocis_credential_t *cocis_auth_find(const cocis_auth_t *auth, const char *username);

/**
 * Attempt a login.
 *
 * On success the session is opened. MUST_CHANGE is returned when the account
 * is valid but the password is still the one-time default; the caller must
 * restrict commands until cocis_auth_change_password succeeds.
 */
cocis_auth_result_t cocis_auth_login(cocis_auth_t *auth, const char *username,
                                     const char *password, uint32_t now_ms,
                                     cocis_pbkdf2_fn pbkdf2);

/** Close the session. */
void cocis_auth_logout(cocis_auth_t *auth);

/**
 * Refresh the idle timer and return the current role.
 * Returns false when there is no session or it has timed out.
 */
bool cocis_auth_session_role(cocis_auth_t *auth, uint32_t now_ms, cocis_role_t *role);

/**
 * Check that the session is valid and has at least `required` privileges.
 * Role order is VIEWER < SECURITY < ADMIN.
 */
bool cocis_auth_require(cocis_auth_t *auth, uint32_t now_ms, cocis_role_t required);

/**
 * Change a password after verifying the old one.
 * `new_salt` must be freshly generated by the caller (target: esp_random).
 */
cocis_auth_result_t cocis_auth_change_password(cocis_auth_t *auth, const char *username,
                                               const char *old_password,
                                               const char *new_password,
                                               const uint8_t new_salt[COCIS_AUTH_SALT_LEN],
                                               uint32_t now_ms,
                                               cocis_pbkdf2_fn pbkdf2);

/** Human readable result for the console/audit log. */
const char *cocis_auth_result_str(cocis_auth_result_t result);
